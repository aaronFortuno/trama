import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { newUniverseReadings } from '../data/readings-new-universes.js';

// One reviewed edition, not an automatic approval command. New editorial
// changes require a fresh independent review before updating this manifest.
const date = '2026-11-20';
const sources = [
  ['data/readings-universe-observatory.js', '99897FD83C1BA4A343E7E51FB720A996BF2A3E661294E7B28F8478B52AF450A9', 'review_universes_observatory_workshop', 249, 253],
  ['data/readings-universe-workshop.js', 'DCD06DA136302997ACFE66020A178B287E4C19951BBB0265AA1BCB8AE3288AFE', 'review_universes_observatory_workshop', 254, 258],
  ['data/readings-universe-newsroom.js', '0DAEB44715312521CE4EC0FC5EA0AAB2A65814DD06CCA7841B93BB7682D4F8FE', 'review_universe_newsroom', 259, 263],
  ['data/readings-universe-riverside.js', 'EE43F56F9EA891024C2B0D4F6C61D682EF94EA0B85607B066A50951445E52B38', 'review_universe_riverside', 264, 268],
];
const hash = content => createHash('sha256').update(content).digest('hex');
for (const [file, expected] of sources) assert.equal(hash(fs.readFileSync(file)), expected.toLowerCase(), `${file}: reviewed source changed`);
assert.equal(newUniverseReadings.length, 40);
const manifest = {
  edition: 'v1.50.3', date,
  scope: 'L249–L268, each Spanish and Catalan version reviewed independently',
  hashScheme: 'SHA256 of UTF-8 JSON.stringify(reading), generated by data/bilingual-reading-model.js; source file hashes record the exact reviewed files',
  teacherValidation: 'pending',
  sources: sources.map(([file, sha256, reviewer]) => ({ file, sha256: sha256.toLowerCase(), reviewer })),
  readings: newUniverseReadings.map(reading => ({
    code: reading.code, language: reading.language, id: reading.id,
    sha256: hash(JSON.stringify(reading)), date, result: 'independent-review-passed',
    status: 'provisional', teacherValidation: 'pending',
    reviewer: sources.find(([, , , start, end]) => +reading.code.slice(1) >= start && +reading.code.slice(1) <= end)[2],
  })),
};
fs.writeFileSync('docs/universes/review-2026-11-20.json', JSON.stringify(manifest, null, 2) + '\n');
console.log(`Recorded ${manifest.readings.length} independently reviewed language versions.`);
